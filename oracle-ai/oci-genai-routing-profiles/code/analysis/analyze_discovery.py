# v1.1 2026-10-10  Brief 14: offline analysis of the read-only probe outputs (ListModelDiscovery vs ListModels vs
#   the docs' Models-by-Region table). v1.1: isOnDemandRetired judged against the probe time (a future retirement
#   date is not 'retired'), models retiring within 30 days listed, ListModels capability filter checked.
#   v1.0: first version. Reads JSON files only; no network, no OCI call.
"""Usage: analyze_discovery.py <probe_dir> <regions_tables_json> <out_md>

Checks, each reported with counts and the model IDs involved:
  A. what ListModelDiscovery returns (vendors, access, capabilities, apiCapability vocabulary, regions);
  B. whether each server-side filter we sent is honoured by the items it returned;
  C. which chat model IDs ListModels (the older API) knows that discovery does not, and the reverse;
  D. on-demand regions per model from discovery vs the docs' Models-by-Region table (xAI and a sample);
  E. retirement/deprecation data discovery carries.
"""
import json
import sys
from collections import Counter
from datetime import datetime, timedelta
from pathlib import Path

PROBE_TIME = ""  # set from md_all.json probed_at_utc

DOC_REGION_NAMES = {  # docs table header -> region identifier (OC1 only)
    "US East (Ashburn) (OC1)": "us-ashburn-1", "US Midwest (Chicago) (OC1)": "us-chicago-1",
    "US West (Phoenix) (OC1)": "us-phoenix-1", "Brazil East (Sao Paulo) (OC1)": "sa-saopaulo-1",
    "Germany Central (Frankfurt) (OC1)": "eu-frankfurt-1", "UK South (London) (OC1)": "uk-london-1",
    "Saudi Arabia Central (Riyadh) (OC1)": "me-riyadh-1", "UAE Central (Abu Dhabi) (OC1)": "me-abudhabi-1",
    "UAE East (Dubai) (OC1)": "me-dubai-1", "India South (Hyderabad) (OC1)": "ap-hyderabad-1",
    "Japan Central (Osaka) (OC1)": "ap-osaka-1",
}


def load(p: Path, name: str) -> dict:
    f = p / f"{name}.json"
    if not f.exists():
        return {"items": None, "error": "missing"}
    return json.loads(f.read_text())


def od_regions(item: dict) -> set:
    return {a["region"] for a in item.get("availability") or [] if "ON_DEMAND" in (a.get("servingModes") or [])}


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    pdir, tables, out = Path(argv[0]), Path(argv[1]), Path(argv[2])
    global PROBE_TIME
    md_all = load(pdir, "md_all")
    md = md_all["items"] or []
    PROBE_TIME = md_all.get("probed_at_utc", "2026-10-10T00:00:00Z")
    L = []
    w = L.append
    w("<!-- v1.1 generated by code/analysis/analyze_discovery.py v1.1 from " + pdir.name + " -->")
    w(f"# Model discovery analysis ({pdir.name})\n")

    # A. overview
    w("## A. What ListModelDiscovery returned (no filters)\n")
    w(f"- models: {len(md)}")
    w(f"- vendors: {dict(Counter(i['vendor'] for i in md))}")
    w(f"- modelAccess: {dict(Counter(i.get('modelAccess') for i in md))}")
    w(f"- capabilities: {dict(Counter(c for i in md for c in i.get('capabilities') or []))}")
    w(f"- apiCapability values seen: {dict(Counter(c for i in md for c in i.get('apiCapability') or []))}")
    w(f"- models with empty apiCapability: {sum(1 for i in md if not i.get('apiCapability'))}")
    regs = Counter(a["region"] for i in md for a in i.get("availability") or [])
    w(f"- regions named in availability: {dict(regs)}")
    w(f"- realms named: {dict(Counter(a.get('realm') for i in md for a in i.get('availability') or []))}")
    w(f"- models with a parameters list: {sum(1 for i in md if i.get('parameters'))}; parameter names: "
      f"{dict(Counter(p['name'] for i in md for p in i.get('parameters') or []))}\n")

    # B. filters honoured?
    w("## B. Are the server-side filters honoured?\n")
    w("| probe | filter sent | items | items that do NOT satisfy the filter |")
    w("|---|---|---|---|")
    checks = {
        "md_region_chat_ondemand": ("region=home, capability=CHAT, servingMode=ON_DEMAND",
                                    lambda i: not ("CHAT" in (i.get("capabilities") or []) and "us-phoenix-1" in od_regions(i))),
        "md_proxy": ("modelAccess=PROXY", lambda i: i.get("modelAccess") != "PROXY"),
        "md_api_responses": ("apiCapability=OPENAI_V1_RESPONSES",
                             lambda i: "OPENAI_V1_RESPONSES" not in (i.get("apiCapability") or [])),
        "md_region_od_not_retired": ("region=home, servingMode=ON_DEMAND, isOnDemandRetired=false",
                                     lambda i: "us-phoenix-1" not in od_regions(i) or any(
                                         (a.get("timeOnDemandRetired") or "9999") <= PROBE_TIME
                                         for a in i.get("availability") or [] if a["region"] == "us-phoenix-1")),
        "md_deprecated": ("isDeprecated=true",
                          lambda i: not any(a.get("timeDeprecated") for a in i.get("availability") or [])),
        "md_realm_oc1": ("realm=oc1", lambda i: not any(a.get("realm") == "oc1" for a in i.get("availability") or [])),
        "md_realm_OC1": ("realm=OC1", lambda i: not any(a.get("realm") == "oc1" for a in i.get("availability") or [])),
    }
    for name, (desc, bad) in checks.items():
        items = load(pdir, name)["items"] or []
        viol = [i["modelId"] for i in items if bad(i)]
        w(f"| {name} | {desc} | {len(items)} | {len(viol)}: {', '.join(viol[:12])}{' ...' if len(viol) > 12 else ''} |")
    w("")

    # C. ListModels vs discovery
    lm = load(pdir, "lm_chat")["items"] or []
    lm_ids = {i["displayName"] for i in lm if i.get("type") == "BASE"}
    md_chat = {i["modelId"] for i in md if "CHAT" in (i.get("capabilities") or [])}
    w("## C. ListModels (capability=CHAT, home region) against discovery (CHAT)\n")
    only_lm = sorted(lm_ids - md_chat)
    only_md = sorted(md_chat - lm_ids)
    w(f"- ListModels base chat IDs: {len(lm_ids)}; discovery chat IDs: {len(md_chat)}")
    w(f"- in ListModels only ({len(only_lm)}):")
    for m in only_lm:
        rec = next(i for i in lm if i["displayName"] == m)
        w(f"  - `{m}` lifecycle={rec.get('lifecycleState')} deprecated={rec.get('timeDeprecated')} "
          f"onDemandRetired={rec.get('timeOnDemandRetired')}")
    w(f"- in discovery only ({len(only_md)}): {', '.join('`'+m+'`' for m in only_md)}")
    notchat = [i["displayName"] for i in lm if "CHAT" not in (i.get("capabilities") or [])]
    w(f"- ListModels was called with capability=CHAT, yet {len(notchat)} of {len(lm)} items are not CHAT models: "
      f"{', '.join(notchat)}\n")

    # D. regions: discovery vs docs table
    w("## D. On-demand regions: discovery against the docs' Models-by-Region table (OC1)\n")
    t = json.loads(tables.read_text())
    doc = {}
    for g in t[1:]:
        hdr = g[0]
        for row in g[1:]:
            for k, h in enumerate(hdr[1:], 1):
                if h in DOC_REGION_NAMES and k < len(row):
                    sym = row[k].replace(" ", "")
                    if sym.startswith("✓") and "d" not in sym.replace("✓", ""):
                        doc.setdefault(row[0], set()).add(DOC_REGION_NAMES[h])
    w("| model (discovery id) | discovery on-demand regions | docs row | docs on-demand regions | same? |")
    w("|---|---|---|---|---|")
    pairs = [("xai.grok-4.20-0309-reasoning", "xAI Grok 4.20"), ("xai.grok-4.3", "xAI Grok 4.3"),
             ("xai.grok-4.6", "xAI Grok 4.6"), ("xai.grok-4.7", "xAI Grok 4.7"),
             ("google.gemini-2.5-flash", "Google Gemini 2.5 Flash"), ("openai.gpt-oss-120b", "OpenAI gpt-oss-120b"),
             ("cohere.command-a-03-2025", "Cohere Command A"), ("meta.llama-3.3-70b-instruct",
                                                                 "Meta Llama 3.3 70B (Standard)")]
    for mid, row in pairs:
        rec = next((i for i in md if i["modelId"] == mid), None)
        a = sorted(od_regions(rec)) if rec else None
        b = sorted(doc.get(row, set()))
        w(f"| `{mid}` | {', '.join(a) if a else 'NOT RETURNED'} | {row} | {', '.join(b) or '-'} | "
          f"{'yes' if a == b else 'NO'} |")
    w("")

    # E. retirement data
    w("## E. Deprecation and retirement data in discovery\n")
    for i in md:
        for a in i.get("availability") or []:
            if a.get("timeDeprecated") or a.get("timeOnDemandRetired") or a.get("supportedReplacements"):
                w(f"- `{i['modelId']}` {a['region']}: deprecated={a.get('timeDeprecated')} "
                  f"onDemandRetired={a.get('timeOnDemandRetired')} dedicatedRetired={a.get('timeDedicatedRetired')} "
                  f"replacements={a.get('supportedReplacements')}")
                break
    w("\n## F. Home-region on-demand models that are not retired yet but retire within 30 days of the probe\n")
    t0 = datetime.strptime(PROBE_TIME, "%Y-%m-%dT%H:%M:%SZ")
    soon = []
    for i in load(pdir, "md_region_od_not_retired")["items"] or []:
        for a in i.get("availability") or []:
            r = a.get("timeOnDemandRetired")
            if a["region"] == "us-phoenix-1" and r:
                d = datetime.strptime(r[:19], "%Y-%m-%dT%H:%M:%S")
                if t0 < d <= t0 + timedelta(days=30):
                    soon.append(f"`{i['modelId']}` ({r[:10]})")
    w(f"- {len(soon)} returned by isOnDemandRetired=false: {', '.join(soon)}")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
